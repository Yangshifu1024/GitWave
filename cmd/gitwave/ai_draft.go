package main

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"gitwave.work/internal/ai"
	"gitwave.work/internal/gitcli"

	"github.com/nsgo-dev/nsgo/core"
)

const (
	defaultHistoryExplain = "You explain Git commits for a human developer. Describe what changed and why it likely matters, " +
		"starting from the commit message and then the diff. Keep it under 200 words. If the diff contradicts the message, " +
		"say so. Base everything strictly on the provided data."
	defaultPRPrompt = "You write pull request titles and descriptions for a human reviewer. " +
		"The first line is the plain-text PR title, at most 72 characters, with no prefix. After one blank line, write " +
		"a Markdown description with a short summary, notable changes and a Testing section. Use only the supplied " +
		"commits and diff. Do not invent changes or wrap the output in Markdown fences."
)

type aiDraftKind uint8

const (
	commitExplanation aiDraftKind = iota
	pullRequestDraft
)

type aiDraftTarget struct {
	kind     aiDraftKind
	sha, ref string
	subject  string
}

type aiDraftForm struct {
	target   aiDraftTarget
	child    *backend
	access   workspaceAI
	request  context.CancelFunc
	pr       gitcli.AIPRContext
	activity *core.Signal[string]
	title    *core.Signal[string]
	body     *core.Signal[string]
	status   *core.Signal[string]
	failure  *core.Signal[string]
}

func (f *aiDraftForm) busy() bool { return f.activity.Get() != "" }

type aiDraftResult struct {
	ai.Outcome
	pr gitcli.AIPRContext
}

func (w *workbench) openCommitExplanation(sha, subject string) {
	if sha != "" {
		w.openAIDraft(aiDraftTarget{kind: commitExplanation, sha: sha, subject: subject})
	}
}

func (w *workbench) openPullRequestDraft() {
	repo := w.repo.Get()
	for _, branch := range repo.Branches {
		if branch.Kind == "local" && branch.Current && repo.Head != "" {
			w.openAIDraft(aiDraftTarget{kind: pullRequestDraft, sha: repo.Head, ref: "refs/heads/" + branch.Name})
			return
		}
	}
}

func (w *workbench) openAIDraft(target aiDraftTarget) {
	if w.core == nil || w.workspaceStore == nil || w.workspaceState.Get().Workspace.ID == "" || w.refreshBlocked() {
		return
	}
	cx := w.cx
	form := &aiDraftForm{target: target, child: w.core, access: w.workspaceAI(),
		activity: core.NewSignal(cx, ""), title: core.NewSignal(cx, ""), body: core.NewSignal(cx, ""),
		status: core.NewSignal(cx, ""), failure: core.NewSignal(cx, "")}
	w.aiDraft.Set(form)
	w.generateAIDraft(form, false)
}

func (w *workbench) closeAIDraft() {
	if form := w.aiDraft.Get(); form != nil {
		if form.request != nil {
			form.request()
		}
		w.aiDraft.Set(nil)
	}
}

func (w *workbench) generateAIDraft(form *aiDraftForm, regenerate bool) {
	if w.aiDraft.Get() != form || w.core != form.child || form.busy() {
		return
	}
	form.activity.Set(w.tr("Generating…", "正在生成…"))
	form.failure.Set("")
	form.status.Set("")
	ctx, cancel := context.WithCancel(w.repoCtx)
	form.request = cancel
	go func() {
		defer cancel()
		outcome, err := form.generate(ctx, regenerate)
		w.cx.Post(func() {
			if w.appCtx.Err() != nil || w.aiDraft.Get() != form || w.core != form.child ||
				w.workspaceState.Get().Workspace.ID != form.access.id {
				return
			}
			form.activity.Set("")
			form.request = nil
			if err != nil {
				if errors.Is(err, ai.ErrNotConfigured) {
					form.failure.Set(w.tr("Configure a provider in Workspace AI settings.", "请先在工作区 AI 设置中配置服务商。"))
				} else {
					form.failure.Set(err.Error())
				}
				return
			}
			if form.target.kind == pullRequestDraft {
				form.pr = outcome.pr
				title, body, _ := strings.Cut(strings.TrimSpace(outcome.Text), "\n")
				form.title.Set(strings.TrimSpace(title))
				form.body.Set(strings.TrimSpace(body))
			} else {
				form.body.Set(outcome.Text)
			}
			provider := fmt.Sprintf(w.tr("Generated by %s.", "由 %s 生成。"), outcome.ProviderUsed)
			if outcome.UsedFallback {
				provider = fmt.Sprintf(w.tr("Generated by fallback provider %s.", "由备用服务商 %s 生成。"), outcome.ProviderUsed)
			}
			form.status.Set(provider)
		})
	}()
}

func (w *workbench) copyAIDraft(form *aiDraftForm, text string) {
	if w.aiDraft.Get() != form || w.core != form.child || form.busy() || form.failure.Get() != "" || strings.TrimSpace(text) == "" {
		return
	}
	if form.target.kind == commitExplanation {
		w.cx.SetClipboard(text)
		return
	}
	form.activity.Set(w.tr("Checking branch and base…", "正在检查源分支和基准分支…"))
	ctx, cancel := context.WithCancel(w.repoCtx)
	form.request = cancel
	snapshot := form.pr
	go func() {
		defer cancel()
		err := form.child.repo.CheckAIPullRequestContext(ctx, snapshot)
		w.cx.Post(func() {
			if w.appCtx.Err() != nil || w.aiDraft.Get() != form || w.core != form.child ||
				w.workspaceState.Get().Workspace.ID != form.access.id {
				return
			}
			form.activity.Set("")
			form.request = nil
			if err != nil {
				form.status.Set("")
				form.failure.Set(w.tr("The branch or base could not be verified. Regenerate before copying.", "无法验证源分支或基准分支。请重新生成后再复制。"))
				return
			}
			w.cx.SetClipboard(text)
		})
	}()
}

func (f *aiDraftForm) generate(ctx context.Context, regenerate bool) (aiDraftResult, error) {
	cfg, err := f.access.configured(ctx)
	if err != nil {
		return aiDraftResult{}, err
	}
	repo := f.child.repo
	rules := repo.AIRules(ctx)
	if f.target.kind == pullRequestDraft {
		head := f.target.sha
		if regenerate {
			current, err := repo.References(ctx)
			if err != nil {
				return aiDraftResult{}, err
			}
			if current.HeadRef != f.target.ref {
				return aiDraftResult{}, errors.New("the active branch changed; reopen the PR description for that branch")
			}
			head = current.Head
		}
		snapshot, err := repo.AIPullRequestContext(ctx, head, f.target.ref)
		if err != nil {
			return aiDraftResult{}, err
		}
		system := cfg.Templates.PR
		if system == "" {
			system = defaultPRPrompt
		}
		result, err := f.access.generate(ctx, cfg, ai.Prompt{System: withAIRepoRules(system, rules), User: snapshot.Context})
		if err != nil {
			return aiDraftResult{}, err
		}
		snapshot.Context = ""
		return aiDraftResult{Outcome: result, pr: snapshot}, repo.CheckAIPullRequestContext(ctx, snapshot)
	}
	user, err := repo.AIExplainCommitContext(ctx, f.target.sha)
	if err != nil {
		return aiDraftResult{}, err
	}
	result, err := f.access.generate(ctx, cfg, ai.Prompt{System: withAIRepoRules(defaultHistoryExplain, rules), User: user})
	return aiDraftResult{Outcome: result}, err
}

func withAIRepoRules(system, rules string) string {
	if rules == "" {
		return system
	}
	return system + "\n\nRepository AI rules (from .gitwave/AI.md):\n" + rules
}
