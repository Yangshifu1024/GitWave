package main

import (
	"context"
	"errors"
	"fmt"

	"gitwave.work/internal/ai"
	"gitwave.work/internal/gitcli"

	"github.com/nsgo-dev/nsgo/core"
)

const defaultCommitPrompt = "You write concise git commit messages. Output ONLY the message text. " +
	"Prefer conventional commits (type: summary). First line <= 72 chars. " +
	"Base the message strictly on the provided staged diff — do not invent changes that are not visible in it. " +
	"Do not wrap in markdown fences."

type commitAIRequest struct {
	cancel context.CancelFunc
}

type commitAIResult struct {
	failure    string
	setup      bool
	suggestion string
	fallback   ai.Provider
}

type commitAIUI struct {
	commitAIRequest *core.Signal[*commitAIRequest]
	commitAIResult  *core.Signal[commitAIResult]
}

func newCommitAIUI(cx *core.Scope) commitAIUI {
	return commitAIUI{
		commitAIRequest: core.NewSignal[*commitAIRequest](cx, nil),
		commitAIResult:  core.NewSignal(cx, commitAIResult{}),
	}
}

func (w *workbench) cancelCommitAI() {
	if request := w.commitAIRequest.Get(); request != nil {
		request.cancel()
		w.commitAIRequest.Set(nil)
	}
	w.commitAIResult.Set(commitAIResult{})
}

func (w *workbench) generateCommitSuggestion() {
	client, child := w.workspaceAI(), w.core
	status := w.changes.Get()
	if client.store == nil || client.id == "" || child == nil || w.commitAIRequest.Get() != nil ||
		w.currentChangesWrite().pending || len(status.staged) == 0 || len(status.conflicts) != 0 {
		return
	}
	w.commitAIResult.Set(commitAIResult{})
	ctx, cancel := context.WithCancel(w.repoCtx)
	request := &commitAIRequest{cancel: cancel}
	w.commitAIRequest.Set(request)
	key, draft := w.changesWriteKey(), w.currentCommitDraft()
	go func() {
		defer cancel()
		outcome, err := func() (ai.Outcome, error) {
			config, err := client.configured(ctx)
			if err != nil {
				return ai.Outcome{}, err
			}
			snapshot, err := child.repo.AICommitContext(ctx, status.status)
			if err != nil {
				return ai.Outcome{}, err
			}
			system := config.Templates.Commit
			if system == "" {
				system = defaultCommitPrompt
			}
			system = withAIRepoRules(system, child.repo.AIRules(ctx))
			result, err := client.generate(ctx, config, ai.Prompt{System: system, User: snapshot.Context})
			if err != nil {
				return ai.Outcome{}, err
			}
			return result, child.repo.CheckAICommitContext(ctx, snapshot)
		}()
		w.cx.Post(func() {
			if w.appCtx.Err() != nil || w.commitAIRequest.Get() != request || w.changesWriteKey() != key || w.core != child {
				return
			}
			w.commitAIRequest.Set(nil)
			if err != nil {
				switch {
				case errors.Is(err, ai.ErrNotConfigured):
					w.commitAIResult.Set(commitAIResult{setup: true})
				case errors.Is(err, gitcli.ErrNoAIStagedChanges):
					w.commitAIResult.Set(commitAIResult{failure: w.tr("Stage files before generating a commit message.", "请先暂存文件，再生成提交信息。")})
				case errors.Is(err, gitcli.ErrAIStagedChanged):
					w.commitAIResult.Set(commitAIResult{failure: w.tr("HEAD or the staged changes changed. Generate another suggestion.", "HEAD 或暂存内容已变化。请重新生成建议。")})
				default:
					w.commitAIResult.Set(commitAIResult{failure: err.Error()})
				}
				return
			}
			result := commitAIResult{}
			if outcome.UsedFallback {
				result.fallback = outcome.ProviderUsed
			}
			if w.currentCommitDraft() == draft {
				w.applyCommitSuggestion(outcome.Text)
			} else {
				result.suggestion = outcome.Text
			}
			w.commitAIResult.Set(result)
		})
	}()
}

func (w *workbench) applyCommitSuggestion(message string) {
	draft := w.currentCommitDraft()
	draft.beforeSuggestion, draft.hasBeforeSuggestion = draft.message, true
	draft.message = message
	w.setCommitDraft(w.changesWriteKey(), draft)
}

func (w *workbench) undoCommitSuggestion() {
	draft := w.currentCommitDraft()
	if !draft.hasBeforeSuggestion {
		return
	}
	draft.message = draft.beforeSuggestion
	draft.beforeSuggestion, draft.hasBeforeSuggestion = "", false
	w.setCommitDraft(w.changesWriteKey(), draft)
}

func (w *workbench) commitAIFallbackText(provider ai.Provider) string {
	return fmt.Sprintf(w.tr("Suggestion generated by fallback provider %s.", "建议由备用服务商 %s 生成。"), provider)
}
